CREATE SEQUENCE conversation_seq START WITH 1000 INCREMENT BY 50;

CREATE TABLE conversation (
    conversation_id bigint      PRIMARY KEY,
    initiator_id    bigint      NOT NULL REFERENCES user_account (user_id),
    business_id     bigint      NOT NULL REFERENCES business (business_id),
    created_at      timestamptz NOT NULL,
    -- One thread per customer and business; its leading column also serves the customer's inbox.
    CONSTRAINT uk_conversation_pair UNIQUE (initiator_id, business_id)
);

CREATE INDEX ix_conversation_business ON conversation (business_id);

CREATE SEQUENCE message_seq START WITH 1000 INCREMENT BY 50;

CREATE TABLE message (
    message_id      bigint        PRIMARY KEY,
    conversation_id bigint        NOT NULL REFERENCES conversation (conversation_id),
    sender_id       bigint        NOT NULL REFERENCES user_account (user_id),
    -- Generated by the client so a retried send is stored once.
    client_uuid     uuid          NOT NULL,
    -- Product the message asks about, when the chat was opened from a product.
    product_id      bigint        REFERENCES product (product_id),
    content         varchar(2000) NOT NULL,
    sent_at         timestamptz   NOT NULL,
    read_at         timestamptz,
    CONSTRAINT uk_message_client_uuid UNIQUE (client_uuid),
    CONSTRAINT ck_message_content CHECK (btrim(content) <> ''),
    CONSTRAINT ck_message_read_after_sent CHECK (read_at IS NULL OR read_at >= sent_at)
);

-- History and "last message" per conversation.
CREATE INDEX ix_message_conversation_sent ON message (conversation_id, sent_at DESC, message_id DESC);
-- Unread badges only scan unread rows.
CREATE INDEX ix_message_unread ON message (conversation_id) WHERE read_at IS NULL;
CREATE INDEX ix_message_sender ON message (sender_id);
CREATE INDEX ix_message_product ON message (product_id) WHERE product_id IS NOT NULL;

CREATE SEQUENCE conversation_report_seq START WITH 1000 INCREMENT BY 50;

CREATE TABLE conversation_report (
    report_id       bigint       PRIMARY KEY,
    conversation_id bigint       NOT NULL REFERENCES conversation (conversation_id),
    reporter_id     bigint       NOT NULL REFERENCES user_account (user_id),
    message_id      bigint       REFERENCES message (message_id),
    reason          varchar(20)  NOT NULL,
    detail          varchar(500),
    status          varchar(10)  NOT NULL DEFAULT 'OPEN',
    created_at      timestamptz  NOT NULL,
    resolved_by     bigint       REFERENCES user_account (user_id),
    resolved_at     timestamptz,
    resolution_note varchar(500),
    CONSTRAINT ck_conversation_report_reason CHECK (reason IN ('SPAM', 'HARASSMENT', 'SCAM', 'OTHER')),
    CONSTRAINT ck_conversation_report_status CHECK (status IN ('OPEN', 'RESOLVED', 'DISMISSED')),
    CONSTRAINT ck_conversation_report_resolution CHECK (
        (status = 'OPEN') = (resolved_at IS NULL) AND (status = 'OPEN') = (resolved_by IS NULL))
);

-- A participant keeps at most one open report per conversation.
CREATE UNIQUE INDEX uk_conversation_report_open ON conversation_report (conversation_id, reporter_id)
    WHERE status = 'OPEN';
CREATE INDEX ix_conversation_report_queue ON conversation_report (status, created_at);
CREATE INDEX ix_conversation_report_reporter ON conversation_report (reporter_id);
CREATE INDEX ix_conversation_report_message ON conversation_report (message_id) WHERE message_id IS NOT NULL;
